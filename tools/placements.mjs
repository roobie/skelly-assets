// Vehicle placements: the part at each site of a vehicle, where it sits in the vehicle frame and whether it is a
// mirrored far-side twin, and the tags the vehicle adds to its body's. Sources are
// models/vehicles/<vehicle>.placements.libsonnet, built from models/vehicles/site.libsonnet; a variant names its parent
// and is laid out from its sites. The why is in docs/decisions/0001-vehicle-placements.md.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { compileJsonnetFile, evaluateJsonnet } from './jsonnet/index.mjs';
import { outputPath } from './layout.mjs';
import { modelProblems } from './taxonomy.mjs';

const repo = resolve(import.meta.dirname, '..');
// Generated by tools/row-index.mjs: every vehicle's placements under its name, variants resolved, and every vehicle's
// own rows.
export const PLACEMENTS_SOURCE = 'models/vehicles/placements.libsonnet';
export const VEHICLE_ROWS_SOURCE = 'models/vehicles/index.libsonnet';
const VEHICLE_KEYS = new Set(['parent', 'sites', 'tags']);
const SITE_KEYS = new Set(['id', 'part', 'at', 'mirror']);

export const placementsPath = (vehicle) => `vehicles/${vehicle}.placements.json`;

// vehicle -> { parent?, sites, tags? }, compiled from the sources.
export const readPlacements = (root = repo) => JSON.parse(compileJsonnetFile(PLACEMENTS_SOURCE, root));

// vehicle -> the ids of the rows its own file authors, from the vehicles' row index. Only the ids are evaluated:
// manifesting the whole rows costs minutes and sits on the full build's path.
export const readVehicleRows = (root = repo) =>
  JSON.parse(evaluateJsonnet(`std.mapWithKey(function(vehicle, rows) [row.id for row in rows], import '${VEHICLE_ROWS_SOURCE}')`, root));

const isPoint = (at) => Array.isArray(at) && at.length === 3 && at.every(Number.isFinite);
const packsByModel = (models) => Map.groupBy(models, ({ id }) => id);

// A vehicle's pack is the one pack that builds the rows of its own file, so a body it borrows from another pack never
// decides where it ships. A variant is built by its parent's file, so it ships in its parent's pack.
function vehiclePack(vehicle, placements, vehicleRows, byModel) {
  const owner = placements[vehicle]?.parent ?? vehicle;
  const packs = [...new Set((vehicleRows[owner] ?? []).flatMap((id) => (byModel.get(id) ?? []).map(({ pack }) => pack)))].sort();
  if (packs.length === 1) return { pack: packs[0] };
  if (packs.length === 0) return { problem: `${vehicle}: no row of ${owner}'s file is built, so it has no pack` };
  return { problem: `${vehicle}: ${owner}'s rows are built in ${packs.length} packs, ${packs.join(' ')}` };
}

// Why a variant cannot be laid out from its parent: its sites come from the parent's and its rows from the parent's
// file, so the parent must be a vehicle of its own.
function parentProblems(vehicle, parent, placements, vehicleRows) {
  if (!Object.hasOwn(placements, parent)) return [`${vehicle}: unknown parent ${parent}`];
  const problems = [];
  if (placements[parent]?.parent !== undefined) problems.push(`${vehicle}: parent ${parent} is itself a variant`);
  if (Object.hasOwn(vehicleRows, vehicle)) problems.push(`${vehicle}: a variant's rows belong in its parent's file`);
  return problems;
}

function siteProblems(vehicle, sites, pack, dependsOn, byModel) {
  const problems = [];
  const seen = new Set();
  const reachable = new Set([pack, ...(dependsOn[pack] ?? [])]);
  for (const site of sites) {
    const where = `${vehicle}/${site?.id}`;
    const unknown = Object.keys(site ?? {}).filter((key) => !SITE_KEYS.has(key));
    if (unknown.length > 0) problems.push(`${where}: unknown keys ${unknown.join(' ')}`);
    if (typeof site?.id !== 'string' || site.id === '') problems.push(`${vehicle}: a site without an id`);
    else if (seen.has(site.id)) problems.push(`${where}: two sites of one id`);
    else seen.add(site.id);
    if (!isPoint(site?.at)) problems.push(`${where}: at is not three finite numbers`);
    if (site?.mirror !== undefined && site.mirror !== true) problems.push(`${where}: mirror is true or absent`);
    const packs = (byModel.get(site?.part) ?? []).map((model) => model.pack);
    if (packs.length === 0) problems.push(`${where}: ${site?.part} is not a built model`);
    if (packs.length > 1) problems.push(`${where}: ${site.part} is built in ${packs.length} packs, ${packs.join(' ')}`);
    if (packs.length === 1 && pack !== undefined && !reachable.has(packs[0])) {
      problems.push(`${where}: ${site.part} is in ${packs[0]}, which ${pack} does not declare a dependency on`);
    }
  }
  return problems;
}

// Why the vehicles could not be assembled from the built models, as messages. placements: vehicle -> { parent?, sites,
// tags? };
// models: the built models, { id, pack }; vehicleRows: vehicle -> its own row ids; dependsOn: pack -> the packs it
// depends on; vocabulary: tools/taxonomy.mjs, readVocabulary. A part is named by its model id alone, so the id must
// name one model, in the vehicle's pack or one it declares a dependency on.
export function placementProblems({ placements, models, vehicleRows, dependsOn, vocabulary }) {
  const byModel = packsByModel(models);
  const problems = [];
  for (const [vehicle, entry] of Object.entries(placements)) {
    const unknown = Object.keys(entry ?? {}).filter((key) => !VEHICLE_KEYS.has(key));
    if (unknown.length > 0) problems.push(`${vehicle}: unknown keys ${unknown.join(' ')}`);
    if (entry?.parent !== undefined) {
      const parentProblem = parentProblems(vehicle, entry.parent, placements, vehicleRows);
      problems.push(...parentProblem);
      if (parentProblem.length > 0) continue;
    }
    const { pack, problem } = vehiclePack(vehicle, placements, vehicleRows, byModel);
    if (problem) problems.push(problem);
    if (entry?.tags !== undefined) {
      problems.push(...modelProblems({ pack: pack ?? '?', id: vehicle, taxonomy: { tags: entry.tags } }, vocabulary).map(({ message }) => message));
    }
    if (!Array.isArray(entry?.sites) || entry.sites.length === 0) problems.push(`${vehicle}: no sites`);
    else problems.push(...siteProblems(vehicle, entry.sites, pack, dependsOn, byModel));
  }
  return problems.sort();
}

// The body's tags, the tags of the root part every other part is placed on, with each vehicle's own added to each facet
// once: a variant's parent's, then its own. One body serves several roles, so a vehicle names what its body cannot.
function vehicleTags(body, ...extras) {
  const tags = { ...body };
  for (const extra of extras) {
    for (const [facet, terms] of Object.entries(extra ?? {})) tags[facet] = [...new Set([...(tags[facet] ?? []), ...terms])];
  }
  return tags;
}

// Writes each vehicle's sites under its own pack. models carry their taxonomy, so each vehicle gets its body's tags.
// Returns the vehicles written, { id, pack, path, tags }, and every file as <pack>/<logical path>.
export function exportPlacements({ placements, models, vehicleRows, dependsOn, vocabulary, out }) {
  const problems = placementProblems({ placements, models, vehicleRows, dependsOn, vocabulary });
  if (problems.length > 0) throw new Error(`vehicle placements:\n  ${problems.join('\n  ')}`);
  const byModel = packsByModel(models);
  const vehicles = Object.entries(placements).sort(([a], [b]) => (a < b ? -1 : 1)).map(([vehicle, { parent, sites, tags }]) => {
    const { pack } = vehiclePack(vehicle, placements, vehicleRows, byModel);
    const path = placementsPath(vehicle);
    const file = join(out, outputPath(pack, path));
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, `${JSON.stringify({ sites }, null, 2)}\n`);
    const [body] = byModel.get(sites[0].part);
    return { id: vehicle, pack, path, tags: vehicleTags(body.taxonomy?.tags, placements[parent]?.tags, tags) };
  });
  return { vehicles, files: vehicles.map(({ pack, path }) => outputPath(pack, path)) };
}
