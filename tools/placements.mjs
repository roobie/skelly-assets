// @ts-check
// Vehicle placements: the part at each site of a vehicle, where it sits in the model frame and whether it is a
// mirrored far-side twin, its title, and the tags the vehicle adds to its body's. Sources are
// models/vehicles/<vehicle>.placements.libsonnet, built from models/vehicles/site.libsonnet; a variant names its parent
// and is laid out from its sites. A site's finish is the paint its copy of the part starts with. The why is in
// docs/decisions/0001-vehicle-placements.md and docs/decisions/0003-vehicle-paint.md.
/** @import { Vec3 } from './packages/construct/src/foundation/math.ts' */
/** @import { Forward } from './packages/thing-core/src/frame.ts' */
/** @import { LoadOutStowage } from './stowage.mjs' */
/** @import { Vocabulary } from './taxonomy.mjs' */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { compileJsonnetFile, evaluateJsonnet } from './jsonnet/index.mjs';
import { outputPath } from './layout.mjs';
import { FORWARDS, toModelFrame } from './packages/thing-core/src/frame.ts';
import { loadOutProblems } from './stowage.mjs';
import { facetTerms, modelProblems, taxonomyTags } from './taxonomy.mjs';
import { titleProblems } from './titles.mjs';

/**
 * A site of a vehicle, as models/vehicles/site.libsonnet writes it.
 * @typedef {object} PlacementSite
 * @property {string} id
 * @property {string} part
 * @property {Vec3} at
 * @property {true} [mirror]
 * @property {string} [finish]
 * @property {string} [rides]
 * @property {Readonly<Record<string, string>>} [stowed] slot id -> item
 * @property {string} [behind]
 */
/**
 * An overlap or contact a vehicle lists, with the text that says why it is correct (`why`) or what is open (`note`).
 * @typedef {{ sites?: readonly string[]; depth?: number; why?: string; note?: string }} ListedOverlap
 */
/** @typedef {Readonly<Record<string, readonly string[]>>} FacetTags facet -> terms */
/**
 * A vehicle's placements.
 * @typedef {object} VehiclePlacements
 * @property {Forward} forward
 * @property {string} [parent]
 * @property {readonly PlacementSite[]} sites
 * @property {FacetTags} [tags]
 * @property {unknown} [title]
 * @property {readonly ListedOverlap[]} [overlaps]
 * @property {readonly ListedOverlap[]} [unjudged]
 * @property {readonly ListedOverlap[]} [swingContacts]
 * @property {readonly ListedOverlap[]} [swingUnjudged]
 */
/** @typedef {Readonly<Record<string, VehiclePlacements>>} Placements vehicle -> its placements */
/** @typedef {Readonly<Record<string, readonly string[]>>} PackLists vehicle -> row ids, or pack -> packs */
/** @typedef {{ id: string; pack: string; paintable?: readonly unknown[] | undefined; taxonomy?: unknown }} PlacedModel */
/** @typedef {ReadonlyMap<string, readonly PlacedModel[]>} ModelsById */

const repo = resolve(import.meta.dirname, '..');
// Generated by tools/row-index.mjs: every vehicle's placements under its name, variants resolved, and every vehicle's
// own rows.
export const PLACEMENTS_SOURCE = 'models/vehicles/placements.libsonnet';
export const VEHICLE_ROWS_SOURCE = 'models/vehicles/index.libsonnet';
const VEHICLE_KEYS = new Set([
  'forward',
  'overlaps',
  'parent',
  'sites',
  'swingContacts',
  'swingUnjudged',
  'tags',
  'title',
  'unjudged',
]);
const SITE_KEYS = new Set(['id', 'part', 'at', 'mirror', 'finish', 'rides', 'stowed', 'behind']);

/** @param {string} vehicle */
export const placementsPath = (vehicle) => `vehicles/${vehicle}.placements.json`;

/**
 * Compiled from the sources.
 * @returns {Placements}
 */
export const readPlacements = (root = repo) => JSON.parse(compileJsonnetFile(PLACEMENTS_SOURCE, root));

/**
 * vehicle -> the ids of the rows its own file authors, from the vehicles' row index. Only the ids are evaluated:
 * manifesting the whole rows costs minutes and sits on the full build's path.
 * @returns {PackLists}
 */
export const readVehicleRows = (root = repo) =>
  JSON.parse(
    evaluateJsonnet(
      `std.mapWithKey(function(vehicle, rows) [row.id for row in rows], import '${VEHICLE_ROWS_SOURCE}')`,
      root,
    ),
  );

/** @param {unknown} at */
const isPoint = (at) => Array.isArray(at) && at.length === 3 && at.every(Number.isFinite);
/**
 * @param {readonly PlacedModel[]} models
 * @returns {ModelsById}
 */
const packsByModel = (models) => Map.groupBy(models, ({ id }) => id);
/** @param {unknown} forward */
const isForward = (forward) => FORWARDS.some((known) => known === forward);

/**
 * A vehicle's pack is the one pack that builds the rows of its own file, so a body it borrows from another pack never
 * decides where it ships. A variant is built by its parent's file, so it ships in its parent's pack.
 * @param {string} vehicle
 * @param {Placements} placements
 * @param {PackLists} vehicleRows
 * @param {ModelsById} byModel
 * @returns {{ pack: string; problem?: never } | { pack?: never; problem: string }}
 */
function vehiclePack(vehicle, placements, vehicleRows, byModel) {
  const owner = placements[vehicle]?.parent ?? vehicle;
  const packs = [
    ...new Set((vehicleRows[owner] ?? []).flatMap((id) => (byModel.get(id) ?? []).map(({ pack }) => pack))),
  ].sort();
  const [only, ...more] = packs;
  if (only !== undefined && more.length === 0) return { pack: only };
  if (packs.length === 0) return { problem: `${vehicle}: no row of ${owner}'s file is built, so it has no pack` };
  return { problem: `${vehicle}: ${owner}'s rows are built in ${packs.length} packs, ${packs.join(' ')}` };
}

/**
 * Why a variant cannot be laid out from its parent: its sites come from the parent's and its rows from the parent's
 * file, so the parent must be a vehicle of its own.
 * @param {string} vehicle
 * @param {string} parent
 * @param {Placements} placements
 * @param {PackLists} vehicleRows
 */
function parentProblems(vehicle, parent, placements, vehicleRows) {
  if (!Object.hasOwn(placements, parent)) return [`${vehicle}: unknown parent ${parent}`];
  const problems = [];
  if (placements[parent]?.parent !== undefined) problems.push(`${vehicle}: parent ${parent} is itself a variant`);
  if (Object.hasOwn(vehicleRows, vehicle)) problems.push(`${vehicle}: a variant's rows belong in its parent's file`);
  return problems;
}

/**
 * Why the carriers the sites name cannot pose their riders: each is another site of the vehicle, and no chain of
 * carriers comes back to its rider.
 * @param {string} vehicle
 * @param {readonly PlacementSite[]} sites
 */
function ridesProblems(vehicle, sites) {
  const carrierOf = new Map(sites.map((site) => [site?.id, site?.rides]));
  return sites.flatMap((site) => {
    if (site?.rides === undefined) return [];
    const where = `${vehicle}/${site.id}`;
    if (site.rides === site.id || !carrierOf.has(site.rides))
      return [`${where}: rides names another site of the vehicle, not ${site.rides}`];
    const chain = [site.id];
    for (
      let /** @type {string | undefined} */ carrier = site.rides;
      carrier !== undefined;
      carrier = carrierOf.get(carrier)
    ) {
      const at = chain.indexOf(carrier);
      if (at === 0) return [`${where}: rides comes back to ${carrier}`];
      if (at > 0) return [];
      chain.push(carrier);
    }
    return [];
  });
}

/**
 * Why a model a site names cannot be placed: it must be one built model, in the vehicle's pack or one the pack depends
 * on.
 * @param {string} where
 * @param {string} id
 * @param {string | undefined} pack
 * @param {ReadonlySet<string | undefined>} reachable
 * @param {ModelsById} byModel
 */
function modelPackProblems(where, id, pack, reachable, byModel) {
  const packs = (byModel.get(id) ?? []).map((model) => model.pack);
  const [only] = packs;
  if (only === undefined) return [`${where}: ${id} is not a built model`];
  if (packs.length > 1) return [`${where}: ${id} is built in ${packs.length} packs, ${packs.join(' ')}`];
  if (pack !== undefined && !reachable.has(only))
    return [`${where}: ${id} is in ${only}, which ${pack} does not declare a dependency on`];
  return [];
}

/**
 * @param {string} vehicle
 * @param {readonly PlacementSite[]} sites
 * @param {string | undefined} pack
 * @param {PackLists} dependsOn
 * @param {ModelsById} byModel
 * @param {object} finishes
 * @param {LoadOutStowage} stowage
 */
function siteProblems(vehicle, sites, pack, dependsOn, byModel, finishes, stowage) {
  const problems = [];
  const seen = new Set();
  const partOf = new Map(sites.map((site) => [site?.id, site?.part]));
  const reachable = new Set([pack, ...((pack === undefined ? undefined : dependsOn[pack]) ?? [])]);
  for (const site of sites) {
    const where = `${vehicle}/${site?.id}`;
    const unknown = Object.keys(site ?? {}).filter((key) => !SITE_KEYS.has(key));
    if (unknown.length > 0) problems.push(`${where}: unknown keys ${unknown.join(' ')}`);
    if (typeof site?.id !== 'string' || site.id === '') problems.push(`${vehicle}: a site without an id`);
    else if (seen.has(site.id)) problems.push(`${where}: two sites of one id`);
    else seen.add(site.id);
    if (!isPoint(site?.at)) problems.push(`${where}: at is not three finite numbers`);
    if (site?.mirror !== undefined && site.mirror !== true) problems.push(`${where}: mirror is true or absent`);
    if (site?.behind !== undefined) {
      const closure = partOf.get(site.behind);
      if (site.behind === site.id || !partOf.has(site.behind))
        problems.push(`${where}: behind names another site of the vehicle, not ${site.behind}`);
      else if (closure === undefined || !stowage.moving.has(closure))
        problems.push(`${where}: behind names ${site.behind}, whose part has no motion to open it`);
    }
    const placed = byModel.get(site?.part) ?? [];
    if (site?.finish !== undefined) {
      if (!Object.hasOwn(finishes, site.finish))
        problems.push(`${where}: finish ${site.finish} is not in the finish library`);
      if (placed.length > 0 && !placed.some(({ paintable }) => (paintable?.length ?? 0) > 0)) {
        problems.push(`${where}: ${site.part} has no paintable slot for finish ${site.finish}`);
      }
    }
    problems.push(...modelPackProblems(where, site?.part, pack, reachable, byModel));
    if (site?.stowed !== undefined) {
      problems.push(...loadOutProblems(where, site, stowage.items));
      const items = new Set(Object.values(site.stowed ?? {}));
      for (const item of items) problems.push(...modelPackProblems(`${where} stowed`, item, pack, reachable, byModel));
    }
  }
  return problems;
}

/**
 * Why the overlaps a vehicle lists (tools/siteOverlap.mjs) cannot be read: each names two different sites of the
 * vehicle, the depth it may reach, and the text (`textKey`) that says why it is correct or what is open about it.
 * @param {string} vehicle
 * @param {string} listKey
 * @param {'why' | 'note'} textKey
 * @param {readonly ListedOverlap[]} listed
 * @param {readonly { id: string }[] | undefined} sites
 * @returns {string[]}
 */
function listedOverlapProblems(vehicle, listKey, textKey, listed, sites) {
  if (!Array.isArray(listed)) return [`${vehicle}: ${listKey} is not a list`];
  const ids = new Set((sites ?? []).map((site) => site?.id));
  return listed.flatMap((entry) => {
    const [a, b] = entry?.sites ?? [];
    const where = `${vehicle}/${a}+${b}`;
    const unknown = Object.keys(entry ?? {}).filter((field) => !['sites', 'depth', textKey].includes(field));
    const text = entry?.[textKey];
    return [
      ...(unknown.length > 0 ? [`${where}: unknown keys ${unknown.join(' ')} in ${listKey}`] : []),
      ...(entry?.sites?.length === 2 && ids.has(a) && ids.has(b) && a !== b
        ? []
        : [`${where}: ${listKey} names two different sites of the vehicle`]),
      ...((entry?.depth ?? 0) > 0 ? [] : [`${where}: ${listKey} needs a depth above 0`]),
      ...(typeof text === 'string' && text !== '' ? [] : [`${where}: ${listKey} needs a ${textKey}`]),
    ];
  });
}

/**
 * Why the vehicles could not be assembled from the built models, as messages. vocabulary is tools/taxonomy.mjs,
 * readVocabulary; finishes is the finish library, keyed by finish id, which the caller loads after the Jsonnet twins are
 * current, so this module never reads them at import; stowage is what the built models say about stowed kit and
 * closures (tools/stowage.mjs, loadOutStowage). A part is named by its model id alone, so the id must name one model,
 * in the vehicle's pack or one it declares a dependency on.
 * @param {object} input
 * @param {Placements} input.placements
 * @param {readonly PlacedModel[]} input.models
 * @param {PackLists} input.vehicleRows vehicle -> its own row ids
 * @param {PackLists} input.dependsOn pack -> the packs it depends on
 * @param {Vocabulary} input.vocabulary
 * @param {object} input.finishes
 * @param {LoadOutStowage} input.stowage
 */
export function placementProblems({ placements, models, vehicleRows, dependsOn, vocabulary, finishes, stowage }) {
  const byModel = packsByModel(models);
  const problems = [];
  for (const [vehicle, entry] of Object.entries(placements)) {
    const unknown = Object.keys(entry ?? {}).filter((key) => !VEHICLE_KEYS.has(key));
    if (unknown.length > 0) problems.push(`${vehicle}: unknown keys ${unknown.join(' ')}`);
    problems.push(
      ...titleProblems({ pack: 'vehicles', id: vehicle, title: entry?.title }).map(({ message }) => message),
    );
    if (!isForward(entry?.forward)) problems.push(`${vehicle}: forward is not one of ${FORWARDS.join(' ')}`);
    if (entry?.parent !== undefined) {
      const parentProblem = parentProblems(vehicle, entry.parent, placements, vehicleRows);
      problems.push(...parentProblem);
      if (parentProblem.length > 0) continue;
    }
    const { pack, problem } = vehiclePack(vehicle, placements, vehicleRows, byModel);
    if (problem) problems.push(problem);
    if (entry?.tags !== undefined) {
      problems.push(
        ...modelProblems({ pack: pack ?? '?', id: vehicle, taxonomy: { tags: entry.tags } }, vocabulary).map(
          ({ message }) => message,
        ),
      );
    }
    if (!Array.isArray(entry?.sites) || entry.sites.length === 0) problems.push(`${vehicle}: no sites`);
    else
      problems.push(
        ...siteProblems(vehicle, entry.sites, pack, dependsOn, byModel, finishes, stowage),
        ...ridesProblems(vehicle, entry.sites),
      );
    if (entry?.overlaps !== undefined)
      problems.push(...listedOverlapProblems(vehicle, 'overlaps', 'why', entry.overlaps, entry?.sites));
    if (entry?.unjudged !== undefined)
      problems.push(...listedOverlapProblems(vehicle, 'unjudged', 'note', entry.unjudged, entry?.sites));
    if (entry?.swingContacts !== undefined)
      problems.push(
        ...listedOverlapProblems(vehicle, 'swingContacts', 'why', entry.swingContacts, [
          ...(entry?.sites ?? []),
          { id: 'ground' },
        ]),
      );
    if (entry?.swingUnjudged !== undefined)
      problems.push(
        ...listedOverlapProblems(vehicle, 'swingUnjudged', 'note', entry.swingUnjudged, [
          ...(entry?.sites ?? []),
          { id: 'ground' },
        ]),
      );
  }
  return problems.sort();
}

/**
 * The body's tags, the tags of the root part every other part is placed on, with each vehicle's own added to each
 * facet once: a variant's parent's, then its own. One body serves several roles, so a vehicle names what its body
 * cannot.
 * @param {unknown} body the body's taxonomy
 * @param {...(FacetTags | undefined)} extras
 */
function vehicleTags(body, ...extras) {
  /** @type {Record<string, unknown>} */
  const tags = { ...taxonomyTags(body) };
  for (const extra of extras) {
    for (const [facet, terms] of Object.entries(extra ?? {}))
      tags[facet] = [...new Set([...facetTerms(tags, facet), ...terms])];
  }
  return tags;
}

/**
 * Writes each vehicle's sites under its own pack. models carry their taxonomy, so each vehicle gets its body's tags. A
 * site that moves carries its `swing` from `swings`, vehicle -> site -> { clear, stop? } (tools/swingClearance.mjs,
 * swingReport): the part of its way to its stop it opens before it touches anything, as a fraction of its motion's
 * clock, and what it touches there.
 * Returns the vehicles written, { id, title, pack, path, tags }, and every file as <pack>/<logical path>.
 * @param {Parameters<typeof placementProblems>[0] & {
 *   swings?: Readonly<Record<string, Readonly<Record<string, object>>>>;
 *   out: string;
 * }} input
 */
export function exportPlacements({
  placements,
  models,
  vehicleRows,
  dependsOn,
  vocabulary,
  finishes,
  stowage,
  swings = {},
  out,
}) {
  const problems = placementProblems({ placements, models, vehicleRows, dependsOn, vocabulary, finishes, stowage });
  if (problems.length > 0) throw new Error(`vehicle placements:\n  ${problems.join('\n  ')}`);
  const byModel = packsByModel(models);
  const vehicles = Object.entries(placements)
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([vehicle, { forward, parent, sites: laid, tags, title }]) => {
      const sites = laid.map((site) => {
        const swing = swings[vehicle]?.[site.id];
        return { ...site, at: toModelFrame(forward, site.at), ...(swing ? { swing } : {}) };
      });
      const { pack, problem } = vehiclePack(vehicle, placements, vehicleRows, byModel);
      if (pack === undefined) throw new Error(problem);
      const path = placementsPath(vehicle);
      const file = join(out, outputPath(pack, path));
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, `${JSON.stringify({ sites }, null, 2)}\n`);
      const root = sites[0]?.part;
      const body = root === undefined ? undefined : byModel.get(root)?.[0];
      if (body === undefined) throw new Error(`${vehicle}: its first site's part is not a built model`);
      const parentTags = parent === undefined ? undefined : placements[parent]?.tags;
      return { id: vehicle, title, pack, path, tags: vehicleTags(body.taxonomy, parentTags, tags) };
    });
  return { vehicles, files: vehicles.map(({ pack, path }) => outputPath(pack, path)) };
}
