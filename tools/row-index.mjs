// Regenerates the index.libsonnet of each folder of row files: the vehicles and the catalogue sets. Jsonnet imports
// must be literal, so a file's rows reach the catalogue only through a generated list; parallel authors each add
// their own files and never touch a shared one.
// Usage: node tools/row-index.mjs
import { mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';
import { compileJsonnetFile } from './jsonnet/index.mjs';

const models = resolve(import.meta.dirname, '../models');
export const ROW_DIRS = [join(models, 'vehicles'), join(models, 'catalogue/sets')];
export const INDEX = 'index.libsonnet';

// Spec files are measures, not rows; a kit is a function or an object of functions, so only a row file is an array.
function rowFiles(dir) {
  const candidates = readdirSync(dir)
    .filter((file) => file.endsWith('.libsonnet') && file !== INDEX && !file.endsWith('.spec.libsonnet'))
    .sort();
  const scratch = mkdtempSync(join(tmpdir(), 'row-index-'));
  const source = join(scratch, 'rows.jsonnet');
  writeFileSync(source, `[${candidates.map((file) => `std.isArray(import ${JSON.stringify(join(dir, file))})`).join(', ')}]\n`);
  try {
    const isRows = JSON.parse(compileJsonnetFile(source));
    return candidates.filter((_, i) => isRows[i]);
  } finally {
    rmSync(scratch, { recursive: true });
  }
}

// The index text: each row file's rows under its file stem, so a recipe can select whole files into its pack.
export function rowIndex(dir) {
  const entries = rowFiles(dir).map((file) => `  '${file.slice(0, -'.libsonnet'.length)}': import '${file}',`);
  return `// Generated by \`tools/row-index.mjs\`.\n{\n${entries.join('\n')}\n}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  for (const dir of ROW_DIRS) writeFileSync(join(dir, INDEX), rowIndex(dir));
}
