// Regenerates the index.libsonnet of each folder of row files, the vehicles and the catalogue sets, and
// models/vehicles/placements.libsonnet. Jsonnet imports must be literal, so a file's rows and a vehicle's placements
// reach the build only through generated lists; parallel authors each add their own files and never touch a shared one.
// Usage: node tools/row-index.mjs
import { mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';
import { compileJsonnetFile } from './jsonnet/index.mjs';

const models = resolve(import.meta.dirname, '../models');
export const VEHICLES_DIR = join(models, 'vehicles');
export const ROW_DIRS = [VEHICLES_DIR, join(models, 'catalogue/sets')];
export const INDEX = 'index.libsonnet';
export const PLACEMENTS = 'placements.libsonnet';
const PLACEMENTS_SUFFIX = '.placements.libsonnet';

const sources = (dir) => readdirSync(dir).filter((file) => file.endsWith('.libsonnet') && file !== INDEX && file !== PLACEMENTS).sort();

// Spec files are measures and placement files place rows, not rows; a kit is a function or an object of functions, so
// only a row file is an array.
function rowFiles(dir) {
  const candidates = sources(dir).filter((file) => !file.endsWith('.spec.libsonnet') && !file.endsWith(PLACEMENTS_SUFFIX));
  const scratch = mkdtempSync(join(tmpdir(), 'row-index-'));
  const source = join(scratch, 'rows.jsonnet');
  writeFileSync(source, `[${candidates.map((file) => `std.isArray(import ${JSON.stringify(join(dir, file))})`).join(', ')}]\n`);
  try {
    const isRows = JSON.parse(compileJsonnetFile(source));
    return candidates.filter((_, i) => isRows[i]);
  } finally {
    rmSync(scratch, { recursive: true });
  }
}

const generated = (entries) => `// Generated by \`tools/row-index.mjs\`.\n{\n${entries.join('\n')}\n}\n`;

// The index text: each row file's rows under its file stem, so a recipe can select whole files into its pack.
export function rowIndex(dir) {
  return generated(rowFiles(dir).map((file) => `  '${file.slice(0, -'.libsonnet'.length)}': import '${file}',`));
}

// The placements index text: each vehicle's placements under its name, for tools/placements.mjs.
export function placementsIndex(dir = VEHICLES_DIR) {
  return generated(sources(dir).filter((file) => file.endsWith(PLACEMENTS_SUFFIX))
    .map((file) => `  '${file.slice(0, -PLACEMENTS_SUFFIX.length)}': import '${file}',`));
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  for (const dir of ROW_DIRS) writeFileSync(join(dir, INDEX), rowIndex(dir));
  writeFileSync(join(VEHICLES_DIR, PLACEMENTS), placementsIndex());
}
